// ============================================================
// Hàm tính cosφ theo công thức Phụ lục Mục 1
// Ap: điện năng tác dụng (kWh), Aq: điện năng phản kháng (kVArh)
// ============================================================
export function tinhCosPhi(Ap: number, Aq: number): number {
  return Ap / Math.sqrt(Ap * Ap + Aq * Aq);
}

// ============================================================
// Hàm tra bảng hệ số k (%) theo giá trị cosφ
// ============================================================
export function traHeSoK(cosPhi: number): number {
  if (cosPhi >= 0.90) return 0;
  // Làm tròn về 2 chữ số thập phân để khớp bảng
  const rounded = Math.round(cosPhi * 100) / 100;
  const row = COSΦ_K_TABLE.find(
    (r) => typeof r.cosφ === "number" && r.cosφ === rounded
  );
  if (row) return row.k;
  if (cosPhi < 0.60) return 52.54;
  return 52.54;
}

// ============================================================
// Hàm tính tiền công suất phản kháng theo công thức Phụ lục Mục 2
// Tp: tiền điện năng tác dụng (chưa VAT), Aq: kVArh, Ap: kWh
// ============================================================
export function tinhTienPhanKhang(Tp: number, Ap: number, Aq: number): number {
  const cosPhi = tinhCosPhi(Ap, Aq);
  const k = traHeSoK(cosPhi);
  return Tp * (k / 100);
}