// ============================================================
// Hàm tính ASDi theo phương pháp sai số công tơ (khoản 2a Điều 21)
// mi: tổng số ngày kỳ hóa đơn, ni: số ngày trộm cắp, AHDi: kWh đã thanh toán, s: sai số %
// ============================================================
export function tinhASDi_SaiSo(mi: number, ni: number, AHDi: number, s: number): number {
  const A_khong_tc = ((mi - ni) / mi) * AHDi;
  const A_co_tc = (AHDi * (ni / mi)) * (1 / (1 - s / 100));
  return A_khong_tc + A_co_tc;
}

// ============================================================
// Hàm tính ASDi phương pháp công suất tổng/biểu đồ phụ tải (Cách 1, 2 — Bước 2 khoản 2c)
// mi: tổng số ngày, ni: số ngày tc, AHDi: kWh đã thanh toán, P: kW, ttb: giờ/ngày
// ============================================================
export function tinhASDi_CongSuatTong(mi: number, ni: number, AHDi: number, P: number, ttb: number): number {
  const A_khong_tc = ((mi - ni) / mi) * AHDi;
  const A_co_tc = P * ttb * ni;
  return A_khong_tc + A_co_tc;
}

// ============================================================
// Hàm tính ASDi phương pháp danh sách thiết bị (Cách 3, 4 — Bước 2 khoản 2c)
// devices: mảng { P_kW, t_h } cho từng thiết bị
// ============================================================
export function tinhASDi_DanhSachThietBi(
  mi: number,
  ni: number,
  AHDi: number,
  devices: { P: number; t: number }[]
): number {
  const A_khong_tc = ((mi - ni) / mi) * AHDi;
  const tongCongSuat = devices.reduce((sum, d) => sum + d.P * d.t, 0);
  const A_co_tc = tongCongSuat * ni;
  return A_khong_tc + A_co_tc;
}

// ============================================================
// Hàm tính số tiền trộm cắp điện ngoài sinh hoạt (khoản 1a Điều 21)
// periods: mảng từng kỳ hóa đơn { AHDi, ASDi, gi }
// ============================================================
export function tinhTienTromCap_NgoaiSinhHoat(
  periods: { AHDi: number; ASDi: number; gi: number }[]
): number {
  return periods.reduce((sum, p) => sum + (p.ASDi - p.AHDi) * p.gi, 0);
}

// ============================================================
// Hàm tính số tiền trộm cắp điện sinh hoạt bậc thang (khoản 1b Điều 21)
// periods: mảng từng kỳ, mỗi kỳ có mảng bậc thang { AHDij, ASDij, gj }
// ============================================================
export function tinhTienTromCap_SinhHoat(
  periods: { bacs: { AHDij: number; ASDij: number; gj: number }[] }[]
): number {
  return periods.reduce((sumI, period) =>
    sumI + period.bacs.reduce((sumJ, bac) =>
      sumJ + (bac.ASDij - bac.AHDij) * bac.gj, 0
    ), 0
  );
}

function parseLawData(text: string, prefix: string): Chapter[] {
  const lines = text.split('\n');
  const chapters: Chapter[] = [];
  
  let currentChapter: any = null;
  let currentSection: any = null;
  let currentArticle: any = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    if (line.match(/^##\s+Chương/i)) {
      if (currentChapter && (!currentChapter.articles || currentChapter.articles.length === 0) && (!currentChapter.sections || currentChapter.sections.length === 0)) {
        currentChapter.articles = [{
          id: currentChapter.id + "-empty",
          number: 0 as any,
          title: currentChapter.title,
          content: "(được bãi bỏ)"
        }];
      }
      let titleText = line.replace(/^##\s*/, '');
      currentChapter = {
        id: prefix + "-CH-" + (chapters.length + 1),
        title: titleText,
        articles: []
      };
      currentSection = null;
      currentArticle = null;
      chapters.push(currentChapter);
    } else if (line.match(/^###\s+Mục/i)) {
      if (currentChapter) {
        let titleText = line.replace(/^###\s*/, '');
        currentSection = {
          id: currentChapter.id + "-S" + ((currentChapter.sections?.length || 0) + 1),
          title: titleText,
          articles: []
        };
        if (!currentChapter.sections) currentChapter.sections = [];
        currentChapter.sections.push(currentSection);
        currentArticle = null;
      }
    } else if (line.match(/^(?:###?\s*)?Điều\s+\d/i) || line.match(/^(?:###?\s*)?PHỤ\s+LỤC\s+[IVX]+/i)) {
      const match = line.match(/^(?:###?\s*)?Điều\s+(\d+[a-zA-Z]*)\.\s*(.+)/i);
      const matchPhuLuc = line.match(/^(?:###?\s*)?(PHỤ\s+LỤC\s+[IVX]+)[\.:]?\s*(.*)/i);
      
      if (match) {
        let numberText = match[1];
        let titleText = line.replace(/^(?:###?)\s*/, '');
        
        currentArticle = {
          id: prefix + "-D" + numberText,
          number: numberText as any, 
          title: titleText,
          content: ""
        };

        if (currentSection) {
          currentSection.articles.push(currentArticle);
        } else if (currentChapter) {
          if (!currentChapter.articles) currentChapter.articles = [];
          currentChapter.articles.push(currentArticle);
        }
      } else if (matchPhuLuc) {
        let numberText = matchPhuLuc[1].replace(/PHỤ\s+LỤC\s+/, '');
        let titleText = matchPhuLuc[2];
        currentArticle = {
          id: prefix + "-PL-" + numberText.replace(/\s+/g, ''),
          number: numberText as any,
          title: titleText,
          content: ""
        };
        if (currentSection) {
          currentSection.articles.push(currentArticle);
        } else if (currentChapter) {
          if (!currentChapter.articles) currentChapter.articles = [];
          currentChapter.articles.push(currentArticle);
        }
      } else {
        let titleText = line.replace(/^(?:###?)\s*/, '');
        currentArticle = {
          id: prefix + "-D-unknown-" + Math.random(),
          number: 0,
          title: titleText,
          content: ""
        };
        if (currentSection) {
          currentSection.articles.push(currentArticle);
        } else if (currentChapter) {
          if (!currentChapter.articles) currentChapter.articles = [];
          currentChapter.articles.push(currentArticle);
        }
      }
    } else {
      if (!currentArticle) {
        currentArticle = {
          id: prefix + "-D-content-" + Math.random(),
          number: 0,
          title: "Nội dung",
          content: line
        };
        if (currentSection) {
          currentSection.articles.push(currentArticle);
        } else if (currentChapter) {
          if (!currentChapter.articles) currentChapter.articles = [];
          currentChapter.articles.push(currentArticle);
        }
      } else {
        if (currentArticle.content) {
          currentArticle.content += "\n\n" + line; 
        } else {
          currentArticle.content = line;
        }
      }
    }
  }

  if (currentChapter && (!currentChapter.articles || currentChapter.articles.length === 0) && (!currentChapter.sections || currentChapter.sections.length === 0)) {
    currentChapter.articles = [{
      id: currentChapter.id + "-empty",
      number: 0 as any,
      title: currentChapter.title,
      content: "(được bãi bỏ)"
    }];
  }

  chapters.forEach((ch: any) => {
    if (ch.sections && ch.sections.length === 0) {
      delete ch.sections;
    }
    if (ch.articles && ch.articles.length === 0) {
      delete ch.articles;
    }
  });

  return chapters;
}

